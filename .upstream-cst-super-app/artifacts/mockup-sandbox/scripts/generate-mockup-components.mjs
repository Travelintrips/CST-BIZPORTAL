import { mkdir, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const artifactRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mockupsRoot = path.join(artifactRoot, "src", "components", "mockups");
const generatedPath = path.join(artifactRoot, "src", ".generated", "mockup-components.ts");

async function discoverMockups(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (entry.name.startsWith("_")) continue;

    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await discoverMockups(absolutePath)));
    } else if (entry.isFile() && entry.name.endsWith(".tsx")) {
      files.push(absolutePath);
    }
  }

  return files;
}

const files = (await discoverMockups(mockupsRoot)).sort();
const entries = files.map((absolutePath) => {
  const relativeFromArtifact = path.relative(artifactRoot, absolutePath).split(path.sep).join("/");
  const globKey = `./${relativeFromArtifact.slice("src/".length)}`;
  const importPath = path.posix.relative("src/.generated", relativeFromArtifact);
  return `  ${JSON.stringify(globKey)}: () => import(${JSON.stringify(importPath)})`;
});

const source = [
  "// This file is auto-generated by scripts/generate-mockup-components.mjs.",
  "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
  "export const modules: ModuleMap = {",
  entries.join(",\n"),
  "};",
  "",
].join("\n");

await mkdir(path.dirname(generatedPath), { recursive: true });
await writeFile(generatedPath, source);