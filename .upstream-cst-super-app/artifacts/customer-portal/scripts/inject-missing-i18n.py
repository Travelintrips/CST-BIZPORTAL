# Helper: generate TS block for airFreight
# ─────────────────────────────────────────────────────────────────────────────

def escape_ts(v):
  # Use single-quoted TS strings; escape single-quote as \'
  v = str(v)
  if "'" in v and '"' not in v:
    return f'"{v}"'
  escaped = v.replace("\\", "\\\\").replace("'", "\\'")
  return f"'{escaped}'"

def af_block(code):
  d = AF.get(code, AF["en-US"])
  lines = ["  airFreight: {"]
  for k, v in d.items():
    lines.append(f"    {k}: {escape_ts(v)},")
  lines.append("  },")
  return "\n".join(lines)

def of_extra_block(code):
  d = of_for_locale(code)
  lines = []
  for k, v in d.items():
    lines.append(f"    {k}: {escape_ts(v)},")
  return "\n".join(lines)

def tp_extra_block(code):
  d = tp_for_locale_wrap(code)
  lines = []
  for k, v in d.items():
    lines.append(f"    {k}: {escape_ts(v)},")
  return "\n".join(lines)

