for code in LOCALE_CODES:
  path = os.path.join(LOCALE_DIR, f"{code}.ts")
  if not os.path.exists(path):
    print(f"  SKIP (not found): {path}")
    continue

  content = open(path, encoding="utf-8").read()

  # ── 1. Skip if airFreight already injected as top-level namespace ──
  # (top-level means 2-space indent: "  airFreight: {")
  # Check by looking at the pattern at start of line with 2 spaces
  if re.search(r'\n  airFreight: \{', content) and "airFreight.back" not in content:
    # Already has the namespace but wrong depth - handle carefully
    pass

  if re.search(r'\n  airFreight: \{', content):
    print(f"  SKIP airFreight (already present): {code}")
  else:
    # Insert airFreight namespace before closing }; of the locale object
    block = af_block(code)
    # The file ends with: \n\n};\n\nexport default locale;\n
    content = re.sub(
      r'\n\n\};\n\nexport default locale;',
      f"\n\n{block}\n\n}};\n\nexport default locale;",
      content
    )
    print(f"  + airFreight namespace: {code}")

  # ── 2. Add oceanFreight extra keys ──
  of_keys_new = of_extra_block(code)
  # Check if already added (look for tradeTypeLabel key in oceanFreight context)
  if "tradeTypeLabel:" in content:
    print(f"  SKIP oceanFreight extras (already present): {code}")
  else:
    # Find last key in oceanFreight namespace: requestFinalQuote
    # Pattern: "    requestFinalQuote: '...',\n  },"
    content = re.sub(
      r"(    requestFinalQuote: [^\n]+,\n  },\n)",
      lambda m: m.group(0).rstrip("}\n,") + "\n" + of_keys_new + "\n  },\n",
      content
    )
    # Handle if requestFinalQuote is the last thing with different spacing
    if "tradeTypeLabel:" not in content:
      # Fallback: search for the oceanFreight closing with custNameRequired
      content = re.sub(
        r"(    custNameRequired: [^\n]+,\n    requestFinalQuote: [^\n]+,\n  },\n)",
        lambda m: m.group(1)[:-3] + "\n" + of_keys_new + "\n  },\n",
        content
      )
    print(f"  + oceanFreight extra keys: {code}")

  # ── 3. Add truckingPage extra keys ──
  tp_keys_new = tp_extra_block(code)
  if "support247:" in content:
    print(f"  SKIP truckingPage extras (already present): {code}")
  else:
    # Find last key in truckingPage namespace: adminReview
    content = re.sub(
      r"(    adminReview: [^\n]+,\n  },\n)",
      lambda m: m.group(1)[:-3] + "\n" + tp_keys_new + "\n  },\n",
      content
    )
    print(f"  + truckingPage extra keys: {code}")

  open(path, "w", encoding="utf-8").write(content)

