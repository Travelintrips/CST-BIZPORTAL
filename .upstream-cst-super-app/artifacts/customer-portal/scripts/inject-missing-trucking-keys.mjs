// en-AU, en-GB, en-SG use same as en-US
const EN = MISSING_KEYS["en-US"];
MISSING_KEYS["en-AU"] = EN;
MISSING_KEYS["en-GB"] = EN;
MISSING_KEYS["en-SG"] = EN;

function esc(str) {
  return str.replace(/\\/g, "\\\\").replace(/'/g, "\\'");
}

function buildBlock(keys) {
  return Object.entries(keys)
    .map(([k, v]) => `    ${k}: '${esc(v)}',`)
    .join("\n");
}

const localeFiles = [
  "ar-AE", "ar-SA", "de-DE", "en-AU", "en-GB", "en-SG", "en-US",
  "es-ES", "fr-FR", "hi-IN", "id-ID", "it-IT", "ja-JP", "ko-KR",
  "ms-MY", "nl-NL", "zh-CN", "zh-TW",
];

let updated = 0;
let skipped = 0;
let alreadyDone = 0;

for (const locale of localeFiles) {
  const filePath = join(LOCALES_DIR, `${locale}.ts`);
  let content;
  try {
    content = readFileSync(filePath, "utf8");
  } catch {
    console.warn(`SKIP: ${locale} not found`);
    skipped++;
    continue;
  }

  const keys = MISSING_KEYS[locale] ?? MISSING_KEYS["en-US"];

  // Find keys that are already present; only inject missing ones
  const missingEntries = Object.fromEntries(
    Object.entries(keys).filter(([k]) => {
      // Check inside truckingPage block specifically
      // Simple check: if key appears anywhere in the file
      const pattern = new RegExp(`\\b${k}:`);
      return !pattern.test(content);
    })
  );

  if (Object.keys(missingEntries).length === 0) {
    console.log(`ALREADY COMPLETE: ${locale}`);
    alreadyDone++;
    continue;
  }

  // Strategy: insert after tambahanOpsional: in the truckingPage block
  // Find the exact tambahanOpsional line with its value
  const tambahanPattern = /(    tambahanOpsional: '[^']*',)/;
  if (!tambahanPattern.test(content)) {
    // Try double quotes variant
    const tambahanPatternDq = /(    tambahanOpsional: "[^"]*",)/;
    if (!tambahanPatternDq.test(content)) {
      console.warn(`WARN: tambahanOpsional not found in ${locale}, skipping`);
      skipped++;
      continue;
    }
    const block = buildBlock(missingEntries).replace(/'/g, '"').replace(/\\'/g, "'");
    content = content.replace(tambahanPatternDq, `$1\n${block}`);
  } else {
    const block = buildBlock(missingEntries);
    content = content.replace(tambahanPattern, `$1\n${block}`);
  }

  writeFileSync(filePath, content, "utf8");
  console.log(`UPDATED: ${locale} (+${Object.keys(missingEntries).length} keys)`);
  updated++;
}

console.log(`\nDone: ${updated} updated, ${alreadyDone} already complete, ${skipped} skipped.`);
