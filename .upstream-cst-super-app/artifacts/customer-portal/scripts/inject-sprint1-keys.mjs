// ─── Inject into locale files ────────────────────────────────────────────────

function buildTruckingAddition(loc) {
  const tr = translations[loc]?.trucking;
  if (!tr) return "";
  return `    errSelectAreas: ${JSON.stringify(tr.errSelectAreas)},\n    errGeneric: ${JSON.stringify(tr.errGeneric)},\n`;
}

function buildJasaDetailSection(loc) {
  const jd = translations[loc]?.jasaDetail;
  if (!jd) return "";
  const lines = Object.entries(jd)
    .map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`)
    .join("\n");
  return `\n  jasaDetail: {\n${lines}\n  },\n`;
}

const localeFiles = [
  "ar-AE", "ar-SA", "de-DE", "en-AU", "en-GB", "en-SG", "en-US",
  "es-ES", "fr-FR", "hi-IN", "id-ID", "it-IT", "ja-JP", "ko-KR",
  "ms-MY", "nl-NL", "zh-CN", "zh-TW",
];

let successCount = 0;
let skipCount = 0;

for (const locale of localeFiles) {
  const filePath = join(LOCALES_DIR, `${locale}.ts`);
  let content;
  try {
    content = readFileSync(filePath, "utf8");
  } catch {
    console.warn(`SKIP: ${locale}.ts not found`);
    skipCount++;
    continue;
  }

  // 1. Add errSelectAreas + errGeneric to truckingPage section
  // Find last key inside truckingPage (the section ending with `  },`)
  // We'll insert before the closing `  },` of truckingPage
  const truckingAddition = buildTruckingAddition(locale);
  if (truckingAddition && !content.includes("errSelectAreas")) {
    // Find the truckingPage section closing — it ends after adminReview key
    const adminReviewPattern = /(\s+adminReview:\s*'[^']*',\s*\n\s*},)/;
    if (adminReviewPattern.test(content)) {
      content = content.replace(adminReviewPattern, (match, p1) => {
        // Insert new keys before closing
        const closing = p1.trimEnd();
        const indent = "    ";
        return `${closing}\n${indent}errSelectAreas: ${JSON.stringify(translations[locale].trucking.errSelectAreas)},\n${indent}errGeneric: ${JSON.stringify(translations[locale].trucking.errGeneric)},\n  },`;
      });
    }
  }

  // 2. Add jasaDetail namespace before the closing `};`
  const jasaDetailSection = buildJasaDetailSection(locale);
  if (jasaDetailSection && !content.includes("jasaDetail:")) {
    // Find the closing `};` or `    };` at end of file
    // Replace the last occurrence of the closing pattern
    const closingPattern = /(\n\s*};[\s\n]*\nexport default locale;)/;
    if (closingPattern.test(content)) {
      content = content.replace(closingPattern, `${jasaDetailSection}\n};\n\nexport default locale;`);
    }
  }

  writeFileSync(filePath, content, "utf8");
  console.log(`✓ ${locale}.ts updated`);
  successCount++;
}

console.log(`\nDone: ${successCount} updated, ${skipCount} skipped`);
