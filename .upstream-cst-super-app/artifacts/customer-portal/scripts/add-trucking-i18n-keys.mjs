const EN_JASA_KEYS = JASA_KEYS["en-US"];

function esc(str) {
  return str.replace(/'/g, "\\'");
}

function buildTruckingBlock(keys) {
  return Object.entries(keys)
    .map(([k, v]) => `    ${k}: '${esc(v)}',`)
    .join("\n");
}

function buildJasaBlock(keys) {
  return Object.entries(keys)
    .map(([k, v]) => `    ${k}: '${esc(v)}',`)
    .join("\n");
}

const localeFiles = [
  "ar-AE", "ar-SA", "de-DE", "en-AU", "en-GB", "en-SG", "en-US",
  "es-ES", "fr-FR", "hi-IN", "id-ID", "it-IT", "ja-JP", "ko-KR",
  "ms-MY", "nl-NL", "zh-CN", "zh-TW",
];

let updated = 0;
let skipped = 0;

for (const locale of localeFiles) {
  const filePath = join(LOCALES_DIR, `${locale}.ts`);
  let content;
  try {
    content = readFileSync(filePath, "utf8");
  } catch {
    console.warn(`SKIP: ${locale} not found`);
    skipped++;
    continue;
  }

  // Skip if keys already injected
  if (content.includes("armadaAktif:")) {
    console.log(`ALREADY DONE: ${locale}`);
    skipped++;
    continue;
  }

  const truckingKeys = TRUCKING_KEYS[locale] ?? EN_KEYS;
  const jasaKeys = JASA_KEYS[locale] ?? EN_JASA_KEYS;

  const truckingBlock = buildTruckingBlock(truckingKeys);
  const jasaBlock = buildJasaBlock(jasaKeys);

  // --- Insert trucking keys after fleet100: line ---
  const fleet100Regex = /( {4}fleet100: '[^']*',)/;
  if (!fleet100Regex.test(content)) {
    console.warn(`WARN: fleet100 not found in ${locale}`);
    skipped++;
    continue;
  }
  content = content.replace(fleet100Regex, `$1\n${truckingBlock}`);

  // --- Insert jasa keys after priceNego: in the jasa section ---
  // Find the jasa section's priceNego line and insert after it
  // We'll look for the pattern: priceNego: '...' within the jasa: { block
  // Use a regex that finds priceNego inside jasa section
  const priceNegoPattern = /(  jasa: \{[\s\S]*?priceNego: '[^']*',)/;
  if (priceNegoPattern.test(content)) {
    content = content.replace(priceNegoPattern, `$1\n${jasaBlock}`);
  } else {
    // Try alternate: find jasa section opening and first priceNego
    const simplePattern = /(    priceNego: "[^"]*",)/;
    if (simplePattern.test(content)) {
      content = content.replace(simplePattern, `$1\n${jasaBlock.replace(/'/g, '"')}`);
    } else {
      console.warn(`WARN: priceNego not found in jasa section for ${locale}`);
    }
  }

  writeFileSync(filePath, content, "utf8");
  console.log(`UPDATED: ${locale}`);
  updated++;
}

console.log(`\nDone: ${updated} updated, ${skipped} skipped.`);
