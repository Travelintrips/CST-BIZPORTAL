function keysToTs(obj) {
  return Object.entries(obj)
    .map(([k, v]) => {
      const escaped = String(v).replace(/'/g, "\\'");
      return `    ${k}: '${escaped}',`;
    })
    .join("\n");
}

function insertAfterPattern(content, afterStr, newLines) {
  const idx = content.indexOf(afterStr);
  if (idx === -1) return null;
  const insertAt = idx + afterStr.length;
  return content.slice(0, insertAt) + "\n" + newLines + content.slice(insertAt);
}

const ALL_LOCALES = [
  "id-ID","en-US","zh-CN","zh-TW","fr-FR","ar-SA","ar-AE",
  "de-DE","es-ES","ja-JP","ko-KR","ms-MY","hi-IN","it-IT","nl-NL",
  "en-AU","en-GB","en-SG",
];

let successCount = 0;
let errors = [];

for (const locale of ALL_LOCALES) {
  const filePath = join(LOCALES_DIR, `${locale}.ts`);
  let content = readFileSync(filePath, "utf8");
  let modified = false;

  // ── 1. oceanFreight keys ──────────────────────────────────────────────────
  const ofKeys = OCEAN_FREIGHT_KEYS[locale];
  if (ofKeys) {
    const alreadyHas = content.includes("heroLine1:");
    if (!alreadyHas) {
      const newBlock = keysToTs(ofKeys);
      // Find errorSubmit: '...' in oceanFreight block then insert after it
      // Strategy: find "errorSubmit:" then find next "  }," after it
      const errorSubmitIdx = content.lastIndexOf("    errorSubmit:");
      if (errorSubmitIdx === -1) {
        errors.push(`${locale}: oceanFreight.errorSubmit not found`);
      } else {
        // Find end of that line
        const lineEnd = content.indexOf("\n", errorSubmitIdx);
        content = content.slice(0, lineEnd + 1) + newBlock + "\n" + content.slice(lineEnd + 1);
        modified = true;
      }
    }
  }

  // ── 2. orders keys ────────────────────────────────────────────────────────
  const ordKeys = ORDERS_KEYS[locale];
  if (ordKeys) {
    const alreadyHas = content.includes("typeLogistic:");
    if (!alreadyHas) {
      const newBlock = keysToTs(ordKeys);
      // Find "emptyStateMsg:" in orders namespace and insert after it
      const emptyStateIdx = content.indexOf("    emptyStateMsg:");
      if (emptyStateIdx === -1) {
        errors.push(`${locale}: orders.emptyStateMsg not found`);
      } else {
        const lineEnd = content.indexOf("\n", emptyStateIdx);
        content = content.slice(0, lineEnd + 1) + newBlock + "\n" + content.slice(lineEnd + 1);
        modified = true;
      }
    }
  }

  // ── 3. marketplaceDetail field keys ───────────────────────────────────────
  const mdKeys = MKT_DETAIL_KEYS[locale];
  if (mdKeys) {
    const alreadyHas = content.includes("fieldServiceType:");
    if (!alreadyHas) {
      const newBlock = keysToTs(mdKeys);
      // Insert after vendorOrdersDone key
      const vendorIdx = content.indexOf("    vendorOrdersDone:");
      if (vendorIdx === -1) {
        errors.push(`${locale}: marketplaceDetail.vendorOrdersDone not found`);
      } else {
        const lineEnd = content.indexOf("\n", vendorIdx);
        content = content.slice(0, lineEnd + 1) + newBlock + "\n" + content.slice(lineEnd + 1);
        modified = true;
      }
    }
  }

  if (modified) {
    writeFileSync(filePath, content, "utf8");
    successCount++;
    console.log(`✓ ${locale}`);
  } else {
    console.log(`- ${locale} (skipped, already up to date or no keys needed)`);
  }
}

console.log(`\nDone. Updated ${successCount} locale files.`);
if (errors.length) {
  console.error("Errors:", errors);
  process.exit(1);
}
