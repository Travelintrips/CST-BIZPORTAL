/**
 * generate-coa-fixture.mjs
 *
 * Queries the PRODUCTION chart_of_accounts and writes a fixture JSON to
 * src/lib/coa-prod-fixture.json. This file is committed to the repo and
 * used by coaDevSync.ts to auto-remap dev COA IDs after a DB reset.
 *
 * Usage (from artifacts/api-server/ directory):
 *   node load-secrets.mjs node scripts/generate-coa-fixture.mjs
 *
 * The script reads SUPABASE_DATABASE_URL (prod). In development mode,
 * load-secrets.mjs overwrites that variable with the dev URL, so you must
 * run this with APP_ENV=production to get the prod fixture:
 *
 *   APP_ENV=production node load-secrets.mjs node scripts/generate-coa-fixture.mjs
 *
 * Commit the updated src/lib/coa-prod-fixture.json to the repo.
 */

import { createRequire } from "module";
import { fileURLToPath } from "url";
import { dirname, join } from "path";
import { writeFileSync } from "fs";

const require = createRequire(import.meta.url);

// Resolve pg from the workspace root where it is guaranteed to be installed
const pgPaths = [
  "/home/runner/workspace/lib/db/node_modules/pg",
  "/home/runner/workspace/node_modules/pg",
];
let pg;
for (const p of pgPaths) {
  try { pg = require(p); break; } catch { /* try next */ }
}
if (!pg) { console.error("Could not find pg module"); process.exit(1); }
const { Pool } = pg;

const __dirname = dirname(fileURLToPath(import.meta.url));
const FIXTURE_PATH = join(__dirname, "../src/lib/coa-prod-fixture.json");

// We explicitly use the PROD URL.
const prodUrl = process.env["SUPABASE_DATABASE_URL"];
if (!prodUrl) {
  console.error(
    "ERROR: SUPABASE_DATABASE_URL not set.\n" +
    "Run via: APP_ENV=production node load-secrets.mjs node scripts/generate-coa-fixture.mjs",
  );
  process.exit(1);
}

const pool = new Pool({
  connectionString: prodUrl,
  ssl: { rejectUnauthorized: false },
  connectionTimeoutMillis: 20000,
});

async function main() {
  const client = await pool.connect();
  try {
    console.log("Querying prod chart_of_accounts...");
    const { rows } = await client.query(
      "SELECT id, code, company_id, name, type::text AS type FROM chart_of_accounts ORDER BY id",
    );
    console.log(`  Found ${rows.length} COA accounts in prod`);

    const fixture = {
      generatedAt: new Date().toISOString(),
      description:
        "Prod COA fixture — auto-generated by scripts/generate-coa-fixture.mjs. " +
        "Commit this file; coaDevSync.ts uses it to fix dev COA IDs after a DB reset.",
      accounts: rows.map((r) => ({
        id: Number(r.id),
        code: r.code,
        companyId: r.company_id !== null ? Number(r.company_id) : null,
        name: r.name,
        type: r.type,
      })),
    };

    writeFileSync(FIXTURE_PATH, JSON.stringify(fixture, null, 2) + "\n");
    const maxId = Math.max(...fixture.accounts.map((a) => a.id));
    console.log(`  Fixture written to: ${FIXTURE_PATH}`);
    console.log(`  Max ID: ${maxId}`);
    console.log("\nDone. Commit src/lib/coa-prod-fixture.json to the repo.");
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((err) => {
  console.error("ERROR:", err);
  process.exit(1);
});
