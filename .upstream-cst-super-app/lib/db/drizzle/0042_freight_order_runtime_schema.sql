-- Canonical freight-order coverage.
--
-- The freight order tables were previously present only in the application
-- schema/runtime history. Keep the bootstrap definition in 0001 for fresh
-- databases and use this additive migration for environments that already
-- recorded 0001.

CREATE TABLE IF NOT EXISTS air_freight_orders (
  id SERIAL PRIMARY KEY,
  order_number TEXT NOT NULL UNIQUE,
  company_id INTEGER REFERENCES companies(id) ON DELETE SET NULL,
  portal_customer_id INTEGER REFERENCES portal_customers(id) ON DELETE SET NULL,
  customer_id INTEGER,
  customer_name TEXT NOT NULL DEFAULT '',
  customer_phone TEXT,
  customer_email TEXT,
  customer_company TEXT,
  origin_city TEXT NOT NULL DEFAULT '',
  origin_airport TEXT NOT NULL DEFAULT '',
  destination_city TEXT NOT NULL DEFAULT '',
  destination_airport TEXT NOT NULL DEFAULT '',
  dest_airport TEXT NOT NULL DEFAULT '',
  trade_type TEXT NOT NULL DEFAULT 'export',
  service_mode TEXT NOT NULL DEFAULT 'airport_to_airport',
  service_level TEXT NOT NULL DEFAULT 'standard',
  incoterm TEXT,
  commodity TEXT,
  hs_code TEXT,
  cargo_type TEXT NOT NULL DEFAULT 'general',
  pieces INTEGER,
  koli INTEGER,
  packing_type TEXT,
  gross_weight NUMERIC(12,3),
  volumetric_weight NUMERIC(12,3),
  total_volumetric_weight NUMERIC(12,3),
  chargeable_weight NUMERIC(12,3),
  volume_cbm NUMERIC(12,3),
  dimension_rows JSONB DEFAULT '[]'::jsonb,
  pickup_date DATE,
  ready_cargo_date DATE,
  preferred_flight_date DATE,
  target_arrival_date DATE,
  etd_requested TEXT,
  additional_services TEXT[],
  selected_additional_services JSONB DEFAULT '[]'::jsonb,
  selected_estimate_option TEXT,
  special_instructions TEXT,
  notes TEXT,
  estimated_price NUMERIC(14,2),
  estimated_price_idr NUMERIC(14,2),
  currency TEXT DEFAULT 'IDR',
  pricing_breakdown JSONB,
  selected_rate_id INTEGER,
  candidate_rate_ids JSONB DEFAULT '[]'::jsonb,
  selected_rfq_submission_id INTEGER,
  final_rate_id INTEGER,
  final_price NUMERIC(14,2),
  final_price_idr NUMERIC(14,2),
  final_rate_per_kg NUMERIC(12,2),
  fuel_surcharge NUMERIC(12,2),
  security_surcharge NUMERIC(12,2),
  awb_fee NUMERIC(12,2),
  handling_fee NUMERIC(12,2),
  xray_fee NUMERIC(12,2),
  doc_fee NUMERIC(12,2),
  customs_clearance_fee NUMERIC(12,2),
  pickup_trucking NUMERIC(12,2),
  delivery_trucking NUMERIC(12,2),
  cargo_surcharge NUMERIC(12,2),
  markup_amount NUMERIC(12,2),
  ppn_pct NUMERIC(5,2) DEFAULT 11,
  ppn_amount NUMERIC(14,2),
  subtotal NUMERIC(14,2) DEFAULT 0,
  grand_total NUMERIC(14,2) DEFAULT 0,
  final_breakdown JSONB,
  admin_notes TEXT,
  airline TEXT,
  flight_number TEXT,
  etd TEXT,
  eta TEXT,
  transit_days INTEGER,
  awb_number TEXT,
  tracking_notes TEXT,
  status TEXT NOT NULL DEFAULT 'inquiry',
  price_status TEXT NOT NULL DEFAULT 'estimate',
  source TEXT NOT NULL DEFAULT 'customer_portal',
  approval_token TEXT UNIQUE,
  approval_token_expires_at TIMESTAMPTZ,
  booking_number TEXT,
  mawb TEXT,
  hawb TEXT,
  decline_reason TEXT,
  declined_at TIMESTAMPTZ,
  approved_at TIMESTAMPTZ,
  admin_quote_attachment_url TEXT,
  quote_token TEXT UNIQUE,
  quote_sent_at TIMESTAMPTZ,
  booking_confirmed_at TIMESTAMPTZ,
  booking_attachment_url TEXT,
  approved_vendor_id INTEGER REFERENCES suppliers(id) ON DELETE SET NULL,
  created_by TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

