CREATE INDEX IF NOT EXISTS air_freight_orders_company_status_idx
  ON air_freight_orders (company_id, status);
CREATE INDEX IF NOT EXISTS air_freight_orders_portal_customer_idx
  ON air_freight_orders (portal_customer_id);
CREATE INDEX IF NOT EXISTS ocean_freight_orders_company_status_idx
  ON ocean_freight_orders (company_id, status);
CREATE INDEX IF NOT EXISTS ocean_freight_orders_portal_customer_idx
  ON ocean_freight_orders (portal_customer_id);

CREATE TABLE IF NOT EXISTS air_freight_tracking_events (
  id SERIAL PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES air_freight_orders(id) ON DELETE CASCADE,
  event_type TEXT NOT NULL,
  note TEXT,
  created_by TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
