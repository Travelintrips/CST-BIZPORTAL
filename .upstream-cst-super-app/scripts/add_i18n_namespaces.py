def find_locale_boundaries(content, locale, all_locales):
    """Find start and end positions of a locale object in translations.ts."""
    start_pattern = f'  "{locale}": {{'
    start_pos = content.find(start_pattern)
    if start_pos == -1:
        return -1, -1
    
    # Find where this locale ends
    next_locale_pos = len(content)
    for loc in all_locales:
        if loc == locale:
            continue
        np = content.find(f'  "{loc}": {{', start_pos + 1)
        if np != -1 and np < next_locale_pos:
            next_locale_pos = np
    
    end_const = content.find("} as const;", start_pos)
    if end_const != -1 and end_const < next_locale_pos:
        next_locale_pos = end_const
    
    segment = content[start_pos:next_locale_pos]
    # Find the last "  }," line (closes the locale object)
    matches = list(re.finditer(r'^  \},?', segment, re.MULTILINE))
    if not matches:
        return -1, -1
    
    last_match = matches[-1]
    close_pos = start_pos + last_match.start()
    return start_pos, close_pos

