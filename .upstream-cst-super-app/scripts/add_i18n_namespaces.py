def apply_overrides(data, locale_overrides, ns_prefix):
    """Apply locale overrides to namespace data dict."""
    result = dict(data)
    prefix = ns_prefix + "_"
    for k, v in locale_overrides.items():
        if k.startswith(prefix):
            result[k[len(prefix):]] = v
    return result

def get_locale_data(locale):
    """Get full data for a locale."""
    if locale in FULL:
        return FULL[locale]
    
    # Start from English base, apply overrides
    base = copy.deepcopy(EN_DATA)
    ov = OVERRIDES.get(locale, {})
    
    result = {}
    for ns in ["pabean", "customClearance", "importCalculator", "mktCard"]:
        ns_prefix = {
            "pabean": "pabean",
            "customClearance": "cc",
            "importCalculator": "calc",
            "mktCard": "mkt",
        }[ns]
        result[ns] = apply_overrides(base[ns], ov, ns_prefix)
    
    return result

def dict_to_ts(d, indent):
    """Convert dict to TypeScript object content lines."""
    lines = []
    ind = " " * indent
    for key, value in d.items():
        if isinstance(value, str):
            escaped = value.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{ind}{key}: "{escaped}",')
        elif isinstance(value, dict):
            lines.append(f'{ind}{key}: {{')
            lines.extend(dict_to_ts(value, indent + 2))
            lines.append(f'{ind}}},')
    return lines

def build_insert_block(locale):
    """Build the text block to insert at end of a locale."""
    data = get_locale_data(locale)
    lines = []
    for ns_name, ns_data in data.items():
        if ns_name == "mktCard":
            continue  # handled separately
        lines.append(f"      {ns_name}: {{")
        for key, value in ns_data.items():
            if isinstance(value, str):
                escaped = value.replace("\\", "\\\\").replace('"', '\\"')
                lines.append(f'        {key}: "{escaped}",')
            elif isinstance(value, dict):
                lines.append(f'        {key}: {{')
                for k2, v2 in value.items():
                    esc2 = str(v2).replace("\\", "\\\\").replace('"', '\\"')
                    lines.append(f'          {k2}: "{esc2}",')
                lines.append(f'        }},')
        lines.append(f"      }},")
    return "\n".join(lines) + "\n"

def build_mktcard_insert(locale):
    """Build the mktCard namespace block to insert."""
    data = get_locale_data(locale)
    mkt = data.get("mktCard", {})
    lines = ["      mktCard: {"]
    for key, value in mkt.items():
        escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        {key}: "{escaped}",')
    lines.append("      },")
    return "\n".join(lines) + "\n"

