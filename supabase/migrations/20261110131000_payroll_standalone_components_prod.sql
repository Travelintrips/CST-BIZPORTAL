-- Standalone Payroll compensation configuration for PROD.
-- Additive only. Existing payroll_runs/items, past approvals, cash advances and GL unchanged.
-- No grants to public/anon/authenticated; backend must set app.payroll_company_id
-- transaction-locally after checking authenticated company membership.
BEGIN;

CREATE TABLE IF NOT EXISTS public.payroll_salary_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL,
  employee_id INTEGER NOT NULL REFERENCES public.employees(id),
  effective_from DATE NOT NULL,
  base_salary NUMERIC(18,2) NOT NULL CHECK (base_salary > 0),
  allowance NUMERIC(18,2) NOT NULL CHECK (allowance >= 0),
  notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT payroll_salary_profiles_unique UNIQUE (company_id,employee_id,effective_from)
);

CREATE TABLE IF NOT EXISTS public.payroll_deduction_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL,
  employee_id INTEGER NOT NULL REFERENCES public.employees(id),
  effective_from DATE NOT NULL,
  code TEXT NOT NULL CHECK (code IN (
    'bpjs_jht_employee','bpjs_kes_employee','pph21','other_deductions','kasbon_deduction'
  )),
  amount NUMERIC(18,2) NOT NULL CHECK (amount >= 0),
  notes TEXT NOT NULL DEFAULT '' CHECK (length(notes) <= 500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT payroll_deduction_settings_unique UNIQUE (company_id,employee_id,effective_from,code)
);

CREATE INDEX IF NOT EXISTS payroll_salary_profiles_company_employee_idx
  ON public.payroll_salary_profiles(company_id,employee_id,effective_from DESC);
CREATE INDEX IF NOT EXISTS payroll_deduction_settings_company_employee_idx
  ON public.payroll_deduction_settings(company_id,employee_id,effective_from DESC);

ALTER TABLE public.payroll_salary_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payroll_salary_profiles FORCE ROW LEVEL SECURITY;
ALTER TABLE public.payroll_deduction_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payroll_deduction_settings FORCE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.payroll_salary_profiles FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.payroll_deduction_settings FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.payroll_salary_profiles_id_seq FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.payroll_deduction_settings_id_seq FROM PUBLIC, anon, authenticated;

CREATE POLICY payroll_salary_profiles_company_scoped
  ON public.payroll_salary_profiles FOR ALL
  USING (company_id = NULLIF(current_setting('app.payroll_company_id', true),'')::integer)
  WITH CHECK (company_id = NULLIF(current_setting('app.payroll_company_id', true),'')::integer);
CREATE POLICY payroll_deduction_settings_company_scoped
  ON public.payroll_deduction_settings FOR ALL
  USING (company_id = NULLIF(current_setting('app.payroll_company_id', true),'')::integer)
  WITH CHECK (company_id = NULLIF(current_setting('app.payroll_company_id', true),'')::integer);

COMMIT;
